import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsBoolean, IsNumber, IsOptional, IsString } from 'class-validator';
import { Type } from 'class-transformer';

export class DhanWebhookDto {
  @ApiProperty({ description: 'Dhan client identification ID', example: '1106885516' })
  @IsString()
  @IsOptional()
  dhanClientId?: string;

  @ApiProperty({ description: 'Unique order identifier generated by Dhan / Exchange', example: '1124112098765' })
  @IsString()
  @IsOptional()
  orderId?: string;

  @ApiPropertyOptional({ description: 'User or alert correlation tag provided during order creation', example: 'nifty_cross_24500' })
  @IsString()
  @IsOptional()
  correlationId?: string;

  @ApiProperty({
    description: 'Current status of the order',
    enum: ['TRANSIT', 'PENDING', 'TRADED', 'REJECTED', 'CANCELLED', 'EXPIRED'],
    example: 'TRADED',
  })
  @IsString()
  @IsOptional()
  orderStatus?: string;

  @ApiProperty({ description: 'Transaction side (BUY / SELL)', example: 'BUY' })
  @IsString()
  @IsOptional()
  transactionType?: string;

  @ApiPropertyOptional({ description: 'Exchange segment', example: 'NSE_FNO' })
  @IsString()
  @IsOptional()
  exchangeSegment?: string;

  @ApiPropertyOptional({ description: 'Product type (INTRADAY, CNC, MARGIN, etc.)', example: 'INTRADAY' })
  @IsString()
  @IsOptional()
  productType?: string;

  @ApiPropertyOptional({ description: 'Order type (MARKET, LIMIT, STOP_LOSS, etc.)', example: 'MARKET' })
  @IsString()
  @IsOptional()
  orderType?: string;

  @ApiPropertyOptional({ description: 'Order validity (DAY, IOC)', example: 'DAY' })
  @IsString()
  @IsOptional()
  validity?: string;

  @ApiPropertyOptional({ description: 'Trading symbol of the instrument', example: 'NIFTY 28 NOV 24500 CALL' })
  @IsString()
  @IsOptional()
  tradingSymbol?: string;

  @ApiPropertyOptional({ description: 'Exchange security identifier', example: '43210' })
  @IsString()
  @IsOptional()
  securityId?: string;

  @ApiPropertyOptional({ description: 'Total requested quantity', example: 50 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  quantity?: number;

  @ApiPropertyOptional({ description: 'Disclosed quantity', example: 0 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  disclosedQuantity?: number;

  @ApiPropertyOptional({ description: 'Order limit price or traded price', example: 142.5 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  price?: number;

  @ApiPropertyOptional({ description: 'Average executed price if traded', example: 142.5 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  averagePrice?: number;

  @ApiPropertyOptional({ description: 'Price trigger that fired the alert / order', example: 24500.0 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  triggerPrice?: number;

  @ApiPropertyOptional({ description: 'After market order indicator', example: false })
  @IsBoolean()
  @IsOptional()
  afterMarketOrder?: boolean;

  @ApiPropertyOptional({ description: 'Bracket order profit value', example: 0.0 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  boProfitValue?: number;

  @ApiPropertyOptional({ description: 'Bracket order stop loss value', example: 0.0 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  boStopLossValue?: number;

  @ApiPropertyOptional({ description: 'Multi-leg order leg name', example: null })
  @IsString()
  @IsOptional()
  legName?: string;

  @ApiPropertyOptional({ description: 'Timestamp when order was created (YYYY-MM-DD HH:MM:SS)', example: '2026-11-20 12:55:00' })
  @IsString()
  @IsOptional()
  createTime?: string;

  @ApiPropertyOptional({ description: 'Timestamp when order was updated (YYYY-MM-DD HH:MM:SS)', example: '2026-11-20 12:55:01' })
  @IsString()
  @IsOptional()
  updateTime?: string;

  @ApiPropertyOptional({ description: 'Timestamp acknowledged by exchange', example: '2026-11-20 12:55:01' })
  @IsString()
  @IsOptional()
  exchangeTime?: string;

  @ApiPropertyOptional({ description: 'Derivative contract expiry date', example: '2026-11-28' })
  @IsString()
  @IsOptional()
  drvExpiryDate?: string;

  @ApiPropertyOptional({ description: 'Derivative option type (CALL / PUT)', example: 'CALL' })
  @IsString()
  @IsOptional()
  drvOptionType?: string;

  @ApiPropertyOptional({ description: 'Derivative strike price', example: 24500.0 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  drvStrikePrice?: number;

  @ApiPropertyOptional({ description: 'OMS error code if order was rejected', example: null })
  @IsString()
  @IsOptional()
  omsErrorCode?: string;

  @ApiPropertyOptional({ description: 'OMS error description if order was rejected', example: null })
  @IsString()
  @IsOptional()
  omsErrorDescription?: string;

  @ApiPropertyOptional({ description: 'Total filled quantity', example: 50 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  filled_qty?: number;

  @ApiPropertyOptional({ description: 'Traded quantity alias', example: 50 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  tradedQuantity?: number;

  @ApiPropertyOptional({ description: 'Algorithm ID if executed via algo trading', example: null })
  @IsString()
  @IsOptional()
  algoId?: string;

  // Optional enrichment fields (if forwarded or passed from custom alert webhooks)
  @ApiPropertyOptional({ description: 'Optional trigger instrument name (e.g. NIFTY 50)', example: 'NIFTY 50' })
  @IsString()
  @IsOptional()
  alertInstrument?: string;

  @ApiPropertyOptional({ description: 'Optional trigger price level where alert was placed', example: 24500.0 })
  @IsNumber()
  @IsOptional()
  @Type(() => Number)
  alertTargetPrice?: number;

  @ApiPropertyOptional({ description: 'Optional alert remarks / notes', example: 'Nifty 24500 breakout' })
  @IsString()
  @IsOptional()
  alertRemarks?: string;
}
